#!/usr/bin/env python3
"""Generate the firmware's anti-aliased UI fonts (ASCII 32..126) as C tables.

Usage:  python3 tools/gen_font.py [out_dir]        (default: components/ui/src/gfx)

Writes font_ui.c from Inter (SIL Open Font License 1.1, https://rsms.me/inter/),
a typeface designed for screens in the same spirit as Apple's San Francisco.
Two faces are produced:
    body   Inter Medium    16 px   (SRS: text at least 16 px high)
    title  Inter SemiBold  30 px
Each glyph is an 8-bit coverage (alpha) bitmap; the renderer blends it over
whatever is on screen. The output is committed, so Pillow and the font files
are only needed when you want to change the look.
"""
import argparse
import os
import sys

from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 32, 126
FACES = [
    # name,   file,              em px, box height, baseline from top of box
    ("body",  "Inter-Medium.otf",   16, 16, 13),
    ("title", "Inter-SemiBold.otf", 30, 32, 26),
]
SEARCH = [
    "/usr/share/fonts/opentype/inter",
    "/usr/share/fonts/truetype/inter",
    "/Library/Fonts",
    os.path.expanduser("~/.fonts"),
    "C:/Windows/Fonts",
]


def find(fname, override):
    if override:
        p = os.path.join(override, fname)
        if os.path.exists(p):
            return p
    for d in SEARCH:
        p = os.path.join(d, fname)
        if os.path.exists(p):
            return p
    sys.exit(f"{fname} not found; pass --fonts DIR (download Inter from https://rsms.me/inter/)")


def build_face(name, path, em, box_h, baseline):
    font = ImageFont.truetype(path, em)
    glyphs, blob = [], bytearray()
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        adv = int(round(font.getlength(ch)))
        bbox = font.getbbox(ch, anchor="ls") if ch != " " else (0, 0, 0, 0)
        l, t, r, b = bbox
        w, h = max(r - l, 0), max(b - t, 0)
        off = len(blob)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255, anchor="ls")
            blob += img.tobytes()
        glyphs.append((off, w, h, l, t, adv))   # t is negative above the baseline
    if len(blob) > 0xFFFF:
        sys.exit(f"{name}: bitmap data {len(blob)} bytes does not fit 16-bit offsets")
    return glyphs, blob


def emit(out, face_data):
    lines = [
        "/* GENERATED by tools/gen_font.py from Inter (SIL OFL 1.1) - do not edit by hand. */",
        '#include "font_ui.h"',
        "",
    ]
    for name, (glyphs, blob), (_n, _f, em, box_h, baseline) in face_data:
        lines.append(f"/* {name}: {em} px em, {len(blob)} bytes of coverage data */")
        lines.append(f"static const uint8_t {name}_bmp[] = {{")
        for i in range(0, len(blob), 24):
            lines.append("    " + ",".join(f"0x{v:02X}" for v in blob[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const font_glyph_t {name}_glyphs[] = {{")
        for code, (off, w, h, xo, yo, adv) in zip(range(FIRST, LAST + 1), glyphs):
            label = chr(code).replace("\\", "backslash").replace("*/", "star-slash")
            lines.append(f"    {{{off}, {w}, {h}, {xo}, {yo}, {adv}}}, /* {label} */")
        lines.append("};")
        lines.append(f"const font_t font_{name} = {{ {box_h}, {baseline}, {name}_glyphs, {name}_bmp }};")
        lines.append("")
    with open(out, "w") as f:
        f.write("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out_dir", nargs="?", default="components/ui/src/gfx")
    ap.add_argument("--fonts", help="directory containing the Inter .otf files")
    a = ap.parse_args()

    data = []
    for spec in FACES:
        name, fname, em, box_h, baseline = spec
        data.append((name, build_face(name, find(fname, a.fonts), em, box_h, baseline), spec))
    out = os.path.join(a.out_dir, "font_ui.c")
    emit(out, data)
    print(f"wrote {out}: " + ", ".join(f"{n} {len(g[1])} B" for n, g, _ in data))


if __name__ == "__main__":
    main()
